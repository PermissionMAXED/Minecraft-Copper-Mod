/**
 * v4 "Inferno Lords": six multi-phase boss fights, each replicating the proven infernoboss
 * architecture (vanilla base entity + {@code core.boss.BossBarHolder} + SpawnGroup.MISC +
 * setPersistent + FabricDefaultAttributeRegistry attributes + summon item + loot table +
 * spawn egg + handbook entries). Every boss has two health phases (ability shift at 50%),
 * a timed special ability and an enrage/defensive stance - see the individual entity
 * classes. Assets (item defs/models/textures, entity textures, loot tables, recipes, lang
 * fragments) are generated by {@code devtools/gen/bosslords_gen.py}.
 */
