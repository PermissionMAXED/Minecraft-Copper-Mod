	private static void registerEntityTypes() {
		// Base dimensions copied 1:1 from the vanilla EntityType registrations (bytecode
		// verified via javap -c on EntityType's <clinit>: iron_golem =
		// dimensions(1.4f, 2.7f); blaze = makeFireImmune().dimensions(0.6f, 1.8f); ghast =
		// makeFireImmune().dimensions(4.0f, 4.0f).eyeHeight(2.6f)
		// .passengerAttachments(4.0625f).vehicleAttachment(0.5f); skeleton =
		// dimensions(0.6f, 1.99f).eyeHeight(1.74f).vehicleAttachment(-0.7f); ravager =
		// dimensions(1.95f, 2.2f).passengerAttachments(new Vec3d(0.0, 2.2625, -0.0625))).
		// The bosses' bulk comes from the SCALE attribute; all get the extended tracking
		// range 10 so the boss bar/model appear well before the fight (infernoboss
		// precedent). Summoned bosses call setPersistent, so MISC (no natural despawn
		// logic) fits all six. Builders are created FRESH per registration.
		THE_SLAG_KING = ModEntities.register("the_slag_king",
				EntityType.Builder.create(TheSlagKingEntity::new, SpawnGroup.MISC)
						.dimensions(1.4f, 2.7f)
						.maxTrackingRange(10));
		EMBER_MATRIARCH = ModEntities.register("ember_matriarch",
				EntityType.Builder.create(EmberMatriarchEntity::new, SpawnGroup.MISC)
						.makeFireImmune()
						.dimensions(0.6f, 1.8f)
						.maxTrackingRange(10));
		ASH_COLOSSUS = ModEntities.register("ash_colossus",
				EntityType.Builder.create(AshColossusEntity::new, SpawnGroup.MISC)
						.dimensions(1.4f, 2.7f)
						.maxTrackingRange(10));
		MAGMA_LEVIATHAN = ModEntities.register("magma_leviathan",
				EntityType.Builder.create(MagmaLeviathanEntity::new, SpawnGroup.MISC)
						.makeFireImmune()
						.dimensions(4.0f, 4.0f)
						.eyeHeight(2.6f)
						.passengerAttachments(4.0625f)
						.vehicleAttachment(0.5f)
						.maxTrackingRange(10));
		CINDER_REAPER = ModEntities.register("cinder_reaper",
				EntityType.Builder.create(CinderReaperEntity::new, SpawnGroup.MISC)
						.dimensions(0.6f, 1.99f)
						.eyeHeight(1.74f)
						.vehicleAttachment(-0.7f)
						.maxTrackingRange(10));
		FORGE_TYRANT = ModEntities.register("forge_tyrant",
				EntityType.Builder.create(ForgeTyrantEntity::new, SpawnGroup.MISC)
						.dimensions(1.95f, 2.2f)
						.passengerAttachments(new Vec3d(0.0, 2.2625, -0.0625))
						.maxTrackingRange(10));
	}

	private static void registerAttributes() {
		// EntityAttributes fields have no GENERIC_ prefix in 1.21.9 (infernoboss precedent,
		// javap-verified); DefaultAttributeContainer.Builder.add(...) overrides base values.
		// MAX_HEALTH spans 240-600, SCALE 1.8-3.5, FOLLOW_RANGE 48-64 across the roster.
		FabricDefaultAttributeRegistry.register(THE_SLAG_KING, IronGolemEntity.createIronGolemAttributes()
				.add(EntityAttributes.MAX_HEALTH, 500.0)
				.add(EntityAttributes.ATTACK_DAMAGE, 20.0)
				.add(EntityAttributes.SCALE, 3.0)
				.add(EntityAttributes.KNOCKBACK_RESISTANCE, 1.0)
				.add(EntityAttributes.FOLLOW_RANGE, 48.0));
		FabricDefaultAttributeRegistry.register(EMBER_MATRIARCH, BlazeEntity.createBlazeAttributes()
				.add(EntityAttributes.MAX_HEALTH, 300.0)
				.add(EntityAttributes.SCALE, 2.2)
				.add(EntityAttributes.FOLLOW_RANGE, 64.0));
		FabricDefaultAttributeRegistry.register(ASH_COLOSSUS, IronGolemEntity.createIronGolemAttributes()
				.add(EntityAttributes.MAX_HEALTH, 550.0)
				.add(EntityAttributes.ATTACK_DAMAGE, 22.0)
				.add(EntityAttributes.SCALE, 3.5)
				.add(EntityAttributes.KNOCKBACK_RESISTANCE, 1.0)
				.add(EntityAttributes.FOLLOW_RANGE, 48.0));
		FabricDefaultAttributeRegistry.register(MAGMA_LEVIATHAN, GhastEntity.createGhastAttributes()
				.add(EntityAttributes.MAX_HEALTH, 400.0)
				.add(EntityAttributes.SCALE, 1.8)
				.add(EntityAttributes.FOLLOW_RANGE, 64.0));
		// Abstract-skeleton attributes carry no ATTACK_DAMAGE base (vanilla skeleton damage
		// comes from the bow), so the melee reaper adds it explicitly for its scythe.
		FabricDefaultAttributeRegistry.register(CINDER_REAPER, AbstractSkeletonEntity.createAbstractSkeletonAttributes()
				.add(EntityAttributes.MAX_HEALTH, 240.0)
				.add(EntityAttributes.ATTACK_DAMAGE, 8.0)
				.add(EntityAttributes.SCALE, 1.8)
				.add(EntityAttributes.FOLLOW_RANGE, 48.0));
		FabricDefaultAttributeRegistry.register(FORGE_TYRANT, RavagerEntity.createRavagerAttributes()
				.add(EntityAttributes.MAX_HEALTH, 600.0)
				.add(EntityAttributes.ATTACK_DAMAGE, 18.0)
				.add(EntityAttributes.SCALE, 2.0)
				.add(EntityAttributes.KNOCKBACK_RESISTANCE, 1.0)
				.add(EntityAttributes.FOLLOW_RANGE, 48.0));
	}

