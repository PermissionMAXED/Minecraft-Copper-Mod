/**
 * v4 "Copper Pantheon" (WP13): six summonable ultra-bosses, each extending a vanilla mob
 * and carrying a boss bar (core.boss.BossBarHolder), two phases, a timed special and an
 * enrage/defensive stance - see the individual entity classes. Every boss has a crafted
 * summon item (shared {@link PantheonSummonItem}; recipes ring the Pantheon Relic
 * catalyst), two drops + one EPIC trophy (loot_table/entities/&lt;boss&gt;.json), a spawn
 * egg in the FAUNA tab and handbook lore + recipe entries. EntityType
 * dimensions/attachments are copied 1:1 from the vanilla registrations (bytecode-verified
 * via javap, chains quoted inline). Assets (item defs/models/textures, entity textures,
 * loot tables, recipes, lang fragments) are generated by
 * {@code devtools/gen/bosspantheon_gen.py}.
 */
