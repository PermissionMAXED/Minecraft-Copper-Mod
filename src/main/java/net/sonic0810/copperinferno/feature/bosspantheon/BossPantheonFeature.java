	private static void registerEntityTypes() {
		// Base dimension chains copied 1:1 from the vanilla EntityType registrations
		// (bytecode-verified via javap -c on EntityType's <clinit>); the bosses' bulk comes
		// from the SCALE attribute, and all six get maxTrackingRange(10) so the model/boss
		// bar appear well before the fight. Summoned bosses call setPersistent, so MISC
		// (no natural despawn logic) fits all of them - the proven infernoboss pattern.
		// evoker = dimensions(0.6f, 1.95f).passengerAttachments(2.0f).vehicleAttachment(-0.6f)
		// .maxTrackingRange(8).notAllowedInPeaceful()
		THE_VERDIGRIS_PROPHET = ModEntities.register("the_verdigris_prophet",
				EntityType.Builder.create(TheVerdigrisProphetEntity::new, SpawnGroup.MISC)
						.dimensions(0.6f, 1.95f)
						.passengerAttachments(2.0f)
						.vehicleAttachment(-0.6f)
						.maxTrackingRange(10));
		// iron_golem = dimensions(1.4f, 2.7f).maxTrackingRange(10)
		PATINA_WARDEN = ModEntities.register("patina_warden",
				EntityType.Builder.create(PatinaWardenEntity::new, SpawnGroup.MISC)
						.dimensions(1.4f, 2.7f)
						.maxTrackingRange(10));
		// ghast = makeFireImmune().dimensions(4.0f, 4.0f).eyeHeight(2.6f)
		// .passengerAttachments(4.0625f).vehicleAttachment(0.5f).maxTrackingRange(10)
		// .notAllowedInPeaceful()
		COIL_HYDRA = ModEntities.register("coil_hydra",
				EntityType.Builder.create(CoilHydraEntity::new, SpawnGroup.MISC)
						.makeFireImmune()
						.dimensions(4.0f, 4.0f)
						.eyeHeight(2.6f)
						.passengerAttachments(4.0625f)
						.vehicleAttachment(0.5f)
						.maxTrackingRange(10));
		// blaze = makeFireImmune().dimensions(0.6f, 1.8f).maxTrackingRange(8)
		// .notAllowedInPeaceful()
		THUNDER_CONDUCTOR = ModEntities.register("thunder_conductor",
				EntityType.Builder.create(ThunderConductorEntity::new, SpawnGroup.MISC)
						.makeFireImmune()
						.dimensions(0.6f, 1.8f)
						.maxTrackingRange(10));
		// slime = dimensions(0.52f, 0.52f).eyeHeight(0.325f).spawnBoxScale(4.0f)
		// .maxTrackingRange(10).notAllowedInPeaceful(); the royal bulk comes from the
		// forced slime SIZE 6 plus the SCALE attribute.
		THE_MINT_KING = ModEntities.register("the_mint_king",
				EntityType.Builder.create(TheMintKingEntity::new, SpawnGroup.MISC)
						.dimensions(0.52f, 0.52f)
						.eyeHeight(0.325f)
						.spawnBoxScale(4.0f)
						.maxTrackingRange(10));
		// vindicator = dimensions(0.6f, 1.95f).passengerAttachments(2.0f)
		// .vehicleAttachment(-0.6f).maxTrackingRange(8).notAllowedInPeaceful()
		GILDED_EXECUTIONER = ModEntities.register("gilded_executioner",
				EntityType.Builder.create(GildedExecutionerEntity::new, SpawnGroup.MISC)
						.dimensions(0.6f, 1.95f)
						.passengerAttachments(2.0f)
						.vehicleAttachment(-0.6f)
						.maxTrackingRange(10));
	}

	private static void registerAttributes() {
		// Every base creator verified via javap; EntityAttributes fields have no GENERIC_
		// prefix in 1.21.9 and DefaultAttributeContainer.Builder.add(...) overrides the base
		// values. MAX_HEALTH 280-500, SCALE 1.8-2.4, FOLLOW_RANGE 48-64 across the roster.
		FabricDefaultAttributeRegistry.register(THE_VERDIGRIS_PROPHET, EvokerEntity.createEvokerAttributes()
				.add(EntityAttributes.MAX_HEALTH, 300.0)
				.add(EntityAttributes.SCALE, 1.8)
				.add(EntityAttributes.FOLLOW_RANGE, 48.0));
		FabricDefaultAttributeRegistry.register(PATINA_WARDEN, IronGolemEntity.createIronGolemAttributes()
				.add(EntityAttributes.MAX_HEALTH, 450.0)
				.add(EntityAttributes.ATTACK_DAMAGE, 17.0)
				.add(EntityAttributes.SCALE, 2.2)
				.add(EntityAttributes.KNOCKBACK_RESISTANCE, 1.0)
				.add(EntityAttributes.FOLLOW_RANGE, 48.0));
		FabricDefaultAttributeRegistry.register(COIL_HYDRA, GhastEntity.createGhastAttributes()
				.add(EntityAttributes.MAX_HEALTH, 320.0)
				.add(EntityAttributes.SCALE, 1.8)
				.add(EntityAttributes.FOLLOW_RANGE, 64.0));
		FabricDefaultAttributeRegistry.register(THUNDER_CONDUCTOR, BlazeEntity.createBlazeAttributes()
				.add(EntityAttributes.MAX_HEALTH, 280.0)
				.add(EntityAttributes.SCALE, 2.4)
				.add(EntityAttributes.FOLLOW_RANGE, 64.0));
		// Slimes have no dedicated creator (vanilla registers HostileEntity attributes and
		// derives stats from the size); TheMintKingEntity.setSize re-asserts the royal
		// statline on top of these bases.
		FabricDefaultAttributeRegistry.register(THE_MINT_KING, HostileEntity.createHostileAttributes()
				.add(EntityAttributes.MAX_HEALTH, 500.0)
				.add(EntityAttributes.SCALE, 1.8)
				.add(EntityAttributes.FOLLOW_RANGE, 48.0));
		FabricDefaultAttributeRegistry.register(GILDED_EXECUTIONER, VindicatorEntity.createVindicatorAttributes()
				.add(EntityAttributes.MAX_HEALTH, 300.0)
				.add(EntityAttributes.ATTACK_DAMAGE, 14.0)
				.add(EntityAttributes.SCALE, 2.0)
				.add(EntityAttributes.FOLLOW_RANGE, 48.0));
	}

