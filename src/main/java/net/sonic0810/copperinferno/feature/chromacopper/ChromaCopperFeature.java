/**
 * v4 "Chromatic Copper" feature: 16 tinted-copper palettes x the 20-block palette template
 * (320 blocks) registered via {@link PaletteSets#registerPaletteSet} into the CHROMATIC
 * creative tab.
 *
 * <p>AUDIT CONTRACT (devtools/audit_assets.py check (f)): every {@code registerPaletteSet}
 * call below passes a STRING LITERAL as the leading palette argument — never a variable or
 * loop value. 16 literal call sites = 16 x 20 audited ids.
 *
 * <p>Assets (blockstates, models, textures, item definitions, loot tables, recipes, EN+DE
 * lang fragments, tag fragment) are generated by {@code devtools/gen/chromacopper_gen.py};
 * the tag fragment lives at {@code devtools/tagfrag/chromacopper.json}.
 *
 * <p>Note: the "gilded" palette is registered as {@code tinted_gilded_copper} because plain
 * {@code gilded_copper_bricks}/{@code _brick_slab}/{@code _brick_stairs}/{@code _brick_wall}
 * already exist (copperdeco feature).
 */
