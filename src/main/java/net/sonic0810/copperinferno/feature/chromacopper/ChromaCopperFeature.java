	// ------------------------------------------------------------------
	// Handbook: one curated page per palette, documenting the base-block dye recipe
	// (recipe id chromacopper/<palette>, 8 copper blocks ringed around one dye -> 8 blocks).
	// ------------------------------------------------------------------

	private static void addPaletteEntry(String palette, String dyeId, String nameEn, String nameDe,
			String dyeEn, String dyeDe) {
		String block = "copper_inferno:" + palette;
		String c = "minecraft:copper_block";
		HandbookEntries.add(new HandbookEntry("blocks", "chromacopper_" + palette,
				block, "chromacopper/" + palette,
				new String[]{c, c, c, c, dyeId, c, c, c, c}, block, 8,
				"Eight Copper Blocks ringed around " + dyeEn + " tint into eight blocks of "
						+ nameEn + ". The stonecutter turns the block into every other shape of the "
						+ "palette (bricks, tiles, slabs, stairs, walls, chiseled, carved, pillar, "
						+ "cut, lamp, lantern); smelting it yields " + nameEn + " Glass.",
				"Acht Kupferbl\u00f6cke, in der Mitte " + dyeDe + " \u2014 das ergibt acht Bl\u00f6cke "
						+ nameDe + ". Die Steins\u00e4ge macht daraus jede weitere Form der Palette "
						+ "(Ziegel, Fliesen, Stufen, Treppen, Mauern, gemei\u00dfelt, verziert, S\u00e4ule, "
						+ "geschnitten, Lampe, Laterne); im Ofen geschmolzen entsteht " + nameDe + "glas."));
	}

