	/**
	 * Copper-like stone profile. Returned SUPPLIER is invoked fresh per registration
	 * ({@code ModBlocks.register} writes a registry key into every settings instance).
	 */
	private static Supplier<AbstractBlock.Settings> chromaStone(MapColor color) {
		return () -> AbstractBlock.Settings.create()
				.mapColor(color)
				.strength(3.0F, 6.0F)
				.requiresTool()
				.sounds(BlockSoundGroup.COPPER);
	}

	/** Fragile tinted glass: glass sounds, nonOpaque, NO requiresTool. */
	private static Supplier<AbstractBlock.Settings> chromaGlass(MapColor color) {
		return () -> AbstractBlock.Settings.create()
				.mapColor(color)
				.strength(0.4F)
				.sounds(BlockSoundGroup.GLASS)
				.nonOpaque();
	}

	/**
	 * Light-source profile shared by {@code <palette>_lamp} and {@code <palette>_lantern}
	 * (PaletteSets feeds BOTH from this one supplier): the lamp glows at 15, the lantern at
	 * 14 — resolved per block state, since only the lantern is a {@link LanternBlock}.
	 */
	private static Supplier<AbstractBlock.Settings> chromaLamp(MapColor color) {
		return () -> AbstractBlock.Settings.create()
				.mapColor(color)
				.strength(3.0F, 6.0F)
				.requiresTool()
				.sounds(BlockSoundGroup.COPPER)
				.luminance(state -> state.getBlock() instanceof LanternBlock ? 14 : 15);
	}

